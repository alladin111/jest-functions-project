const { sum, multiply, divide, isEven } = require('./mathFunctions');

describe('Функция sum', () => {
  test('sum: возвращает корректную сумму двух чисел', () => {
    // toBe – проверяет строгое равенство значений (Object.is)
    expect(sum(2, 3)).toBe(5);
  });

  test('sum: корректно работает с отрицательными числами', () => {
    // toBe – проверяет строгое равенство значений
    expect(sum(-5, -3)).toBe(-8);
    // toBe – проверяет строгое равенство значений
    expect(sum(-5, 3)).toBe(-2);
  });
});

describe('Функция multiply', () => {
  test('multiply: возвращает корректное произведение', () => {
    // toBe – проверяет строгое равенство значений
    expect(multiply(4, 5)).toBe(20);
  });

  test('multiply: возвращает 0 при умножении на 0', () => {
    // toBe – проверяет строгое равенство значений (ожидаем 0)
    expect(multiply(7, 0)).toBe(0);
    // toBe – проверяет строгое равенство значений (ожидаем 0)
    expect(multiply(0, 7)).toBe(0);
  });
});

describe('Функция divide', () => {
  test('divide: возвращает корректный результат деления', () => {
    // toBe – проверяет строгое равенство значений
    expect(divide(10, 2)).toBe(5);
    // toBe – проверяет строгое равенство значений
    expect(divide(9, 3)).toBe(3);
  });

  test('divide: выбрасывает ошибку при делении на 0', () => {
    // toThrow – проверяет, что функция выбрасывает исключение
    expect(() => divide(10, 0)).toThrow();
    // toThrow – проверяет, что функция выбрасывает исключение с конкретным сообщением
    expect(() => divide(10, 0)).toThrow('Деление на ноль невозможно');
  });
});

describe('Функция isEven', () => {
  test('isEven: возвращает true для чётных чисел', () => {
    // toBe – проверяет строгое равенство значений (ожидаем true)
    expect(isEven(4)).toBe(true);
    // toBe – проверяет строгое равенство значений (0 тоже чётное)
    expect(isEven(0)).toBe(true);
    // toBe – проверяет строгое равенство значений (отрицательное чётное)
    expect(isEven(-6)).toBe(true);
  });

  test('isEven: возвращает false для нечётных чисел', () => {
    // toBe – проверяет строгое равенство значений (ожидаем false)
    expect(isEven(5)).toBe(false);
    // toBe – проверяет строгое равенство значений (отрицательное нечётное)
    expect(isEven(-3)).toBe(false);
    // toBe – проверяет строгое равенство значений (ожидаем false)
    expect(isEven(7)).toBe(false);
  });
});